uint32_t DecodeUtf8Codepoint(const char*& p, size_t& remaining) {
    if (remaining == 0) return 0;
    unsigned char c = static_cast<unsigned char>(*p);
    p++;
    remaining--;

    if (c < 0x80) {
        return c;
    }
    // 2-byte UTF-8 (Russian А-я)
    if ((c & 0xE0) == 0xC0) {
        if (remaining < 1) return '?';
        unsigned char c2 = static_cast<unsigned char>(*p);
        p++;
        remaining--;
        return ((c & 0x1F) << 6) | (c2 & 0x3F);
    }
    // 3-byte UTF-8 (Symbols ❤, ★, ✓, ♫)
    if ((c & 0xF0) == 0xE0) {
        if (remaining < 2) return '?';
        unsigned char c2 = static_cast<unsigned char>(*p);
        p++;
        remaining--;
        unsigned char c3 = static_cast<unsigned char>(*p);
        p++;
        remaining--;
        return ((c & 0x0F) << 12) | ((c2 & 0x3F) << 6) | (c3 & 0x3F);
    }
    // 4-byte UTF-8 (Emojis 💬, 🗨, 🔥)
    if ((c & 0xF8) == 0xF0) {
        if (remaining < 3) return '?';
        unsigned char c2 = static_cast<unsigned char>(*p);
        p++;
        remaining--;
        unsigned char c3 = static_cast<unsigned char>(*p);
        p++;
        remaining--;
        unsigned char c4 = static_cast<unsigned char>(*p);
        p++;
        remaining--;
        return ((c & 0x07) << 18) | ((c2 & 0x3F) << 12) | ((c3 & 0x3F) << 6) | (c4 & 0x3F);
    }
    return '?';
}

const uint8_t* GetGlyphBitmap(uint32_t codepoint) {
    // ASCII Range (32..126)
    if (codepoint >= 32 && codepoint <= 126) {
        return s_FontAscii[codepoint - 32];
    }
    // Russian Uppercase: 0x0410 (А) .. 0x042F (Я)
    if (codepoint >= 0x0410 && codepoint <= 0x042F) {
        return s_FontCyrillic[codepoint - 0x0410];
    }
    // Russian Ё (0x0401)
    if (codepoint == 0x0401) {
        return s_FontCyrillic[32];
    }
    // Russian Lowercase: 0x0430 (а) .. 0x044F (я)
    if (codepoint >= 0x0430 && codepoint <= 0x044F) {
        return s_FontCyrillic[33 + (codepoint - 0x0430)];
    }
    // Russian ё (0x0451)
    if (codepoint == 0x0451) {
        return s_FontCyrillic[65];
    }
    // Xbox icons (Private Unicode: 0xE000 .. 0xE007)
    if (codepoint >= 0xE000 && codepoint <= 0xE007) {
        return s_FontXboxIcons[codepoint - 0xE000];
    }

    // Social UI glyphs
    // Heart: ❤ (0x2764) or ♥ (0x2665)
    if (codepoint == 0x2764 || codepoint == 0x2665) {
        return s_GlyphHeart;
    }
    // Comment bubble: 💬 (0x1F4AC) or 🗨 (0x1F5E8) or 0x25C9
    if (codepoint == 0x1F4AC || codepoint == 0x1F5E8 || codepoint == 0x25C9) {
        return s_GlyphComment;
    }
    // Music notes: ♫ (0x266A, 0x266B)
    if (codepoint == 0x266A || codepoint == 0x266B) {
        return s_GlyphMusic;
    }
    // Online circle: ● (0x25CF)
    if (codepoint == 0x25CF || codepoint == 0x2022) {
        return s_GlyphDotOnline;
    }
    // Checkmark: ✓ (0x2713, 0x2714)
    if (codepoint == 0x2713 || codepoint == 0x2714) {
        return s_GlyphCheckmark;
    }
    // Coin / Star: ★ (0x2605)
    if (codepoint == 0x2605) {
        return s_GlyphCoin;
    }
    // Arrows
    if (codepoint == 0x25B2) return s_GlyphArrowUp;
    if (codepoint == 0x25BC) return s_GlyphArrowDown;

    // Fallback: question mark
    return s_FontAscii['?' - 32];
}

